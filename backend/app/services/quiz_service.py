import json
import logging
from typing import Dict, Any, List, Optional
from app.services.gemini_service import get_gemini_service
from app.utils.text_chunker import get_focused_context

logger = logging.getLogger(__name__)

class QuizService:
    @staticmethod
    def generate_quiz_questions(
        subject: str,
        topic: str,
        difficulty: str = "Medium",
        count: int = 5,
        is_mock_test: bool = False,
        source_context: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Prompts Gemini to generate high-quality multiple choice academic questions.
        """
        gemini = get_gemini_service()

        context_prompt = ""
        if source_context:
            focused = get_focused_context(source_context, query=f"{subject} {topic}", max_chars=4000)
            context_prompt = f"\nUse this course material as the primary ground-truth source:\n'''\n{focused}\n'''\n"

        prompt = f"""
Generate an academic Multiple Choice Quiz for:
Subject: {subject}
Topic: {topic}
Difficulty: {difficulty}
Number of questions: {count}
Mock Test Mode: {"Yes - Comprehensive test simulation" if is_mock_test else "No - Concept Practice"}
{context_prompt}

Requirements:
- Each question must be academically accurate, clear, and challenging for university/college exam prep.
- Provide exactly 4 options labeled "A", "B", "C", "D".
- Specify the correct option ('A', 'B', 'C', or 'D').
- Provide a clear, educational explanation why the answer is correct and why other options are incorrect.
- Identify the specific sub-concept or topic for each question.

Return a JSON array of objects with the exact schema:
[
  {{
    "id": 1,
    "question": "Clear academic question text?",
    "options": [
      {{"id": "A", "text": "Option text 1"}},
      {{"id": "B", "text": "Option text 2"}},
      {{"id": "C", "text": "Option text 3"}},
      {{"id": "D", "text": "Option text 4"}}
    ],
    "correct_option": "A",
    "explanation": "In-depth explanation of the concept...",
    "topic": "Specific sub-topic"
  }}
]
"""
        raw_json = gemini.generate_structured_json(
            prompt=prompt,
            system_instruction="You are a university examination board expert creating rigorous, syllabus-aligned multiple choice questions."
        )

        if isinstance(raw_json, dict):
            for k in ["questions", "quiz", "data", "mcqs"]:
                if k in raw_json and isinstance(raw_json[k], list):
                    raw_json = raw_json[k]
                    break
            else:
                for v in raw_json.values():
                    if isinstance(v, list):
                        raw_json = v
                        break

        if not isinstance(raw_json, list) or len(raw_json) == 0:
            raise ValueError("Invalid quiz structure generated by AI.")

        # Validate and sanitize each question
        sanitized_questions = []
        for idx, item in enumerate(raw_json, 1):
            q_id = item.get("id", idx)
            q_text = item.get("question", "").strip()
            raw_options = item.get("options", [])
            correct_opt = str(item.get("correct_option", "A")).strip().upper()
            explanation = item.get("explanation", "Correct based on subject principles.").strip()
            subtopic = item.get("topic", topic).strip()

            if not q_text or len(raw_options) != 4:
                continue

            clean_options = []
            for opt in raw_options:
                opt_id = str(opt.get("id", "")).strip().upper()
                opt_text = str(opt.get("text", "")).strip()
                if opt_id and opt_text:
                    clean_options.append({"id": opt_id, "text": opt_text})

            if len(clean_options) != 4:
                continue

            sanitized_questions.append({
                "id": q_id,
                "question": q_text,
                "options": clean_options,
                "correct_option": correct_opt,
                "explanation": explanation,
                "topic": subtopic
            })

        if not sanitized_questions:
            raise ValueError("Could not extract valid questions from generated AI response.")

        return sanitized_questions

    @staticmethod
    def evaluate_quiz(
        stored_questions: List[Dict[str, Any]],
        user_answers: List[Dict[str, Any]]
    ) -> Dict[str, Any]:
        """
        Evaluates submitted answers against stored correct answers on the backend.
        Never trusts client-submitted scores.
        """
        # Map stored questions by ID
        questions_map = {q["id"]: q for q in stored_questions}
        answers_map = {a.get("question_id"): a.get("selected_option") for a in user_answers}

        total_questions = len(stored_questions)
        score = 0
        review_items = []
        weak_topics = set()

        for q in stored_questions:
            q_id = q["id"]
            correct_opt = str(q.get("correct_option", "")).upper()
            user_opt = answers_map.get(q_id)
            user_opt_clean = str(user_opt).upper() if user_opt else None

            is_correct = (user_opt_clean == correct_opt)
            if is_correct:
                score += 1
            else:
                topic_name = q.get("topic")
                if topic_name:
                    weak_topics.add(topic_name)

            review_items.append({
                "question_id": q_id,
                "question": q["question"],
                "options": q["options"],
                "selected_option": user_opt_clean,
                "correct_option": correct_opt,
                "is_correct": is_correct,
                "explanation": q.get("explanation", ""),
                "topic": q.get("topic")
            })

        percentage = round((score / total_questions) * 100, 1) if total_questions > 0 else 0.0

        topics_to_review = list(weak_topics)
        if not topics_to_review and percentage == 100.0:
            topics_to_review = ["Outstanding mastery! Keep revising advanced problem sets."]

        return {
            "score": score,
            "total_questions": total_questions,
            "percentage": percentage,
            "topics_to_review": topics_to_review,
            "review": review_items
        }

